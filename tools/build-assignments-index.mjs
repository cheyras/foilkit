// tools/build-assignments-index.mjs — derive the workbench resolver's
// per-card/per-set assignment index from the research corpus.
//
//   data/foil-card-assignments.json  (canonical, cited, hand-reviewed)
//     └─► packages/resolver/src/assignments-index.json  (trimmed, bundle-friendly)
//
// The evidence file carries full claims + cited sources; the shipped index
// only needs the selectors (setIds / cls / rarities / variantKinds / cardIds /
// facet), the pattern, confidence, and citation hostnames. Regenerate after ANY
// change to the evidence file:   node tools/build-assignments-index.mjs
//
// Selector semantics (mirrored by resolver.ts resolveFoil v3):
//   facet rows  — catalog-wide: variant kind declares an explicit foil facet
//                 (e.g. holo-foil-cosmos → 'cosmos'); most specific after cardIds.
//   set rows    — match (setId, cls) plus optional rarities / variantKinds /
//                 cardIds narrowing. cls ∈ holo|reverse|full-foil|normal+facet.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'data', 'foil-card-assignments.json');
const OUT = join(root, 'packages', 'resolver', 'src', 'assignments-index.json');

const src = JSON.parse(readFileSync(SRC, 'utf8'));

const hosts = (sources) => [
  ...new Set(sources.map((s) => new URL(s.url).hostname.replace(/^www\./, ''))),
];

// 'normal' (R2, 2026-08-02): a card-level-ONLY class for subset cards the
// catalog declares as plain prints but which physically carry a foil
// treatment (e.g. Radiant Collection commons — dot overprint, no aluminum).
// The resolver consults these rows before its scope-none early return.
const CLASSES = new Set(['holo', 'reverse', 'full-foil', 'normal+facet', 'normal']);
const CONF = new Set(['high', 'medium', 'low']);
// Per-row scope override (R2b, 2026-08-02): treatments whose physical extent
// the variant kind/rarity cannot express (baby shinies = window despite a
// full-foil rarity; VSTAR pearl = full face despite a plain holo kind).
const SCOPES = new Set(['window', 'full', 'sheet']);

const facets = {};
for (const r of src.facet_rows) {
  if (!CONF.has(r.confidence)) throw new Error(`facet ${r.facet}: bad confidence`);
  if (facets[r.facet])
    throw new Error(`facet ${r.facet}: duplicate row — the resolver needs exactly one mapping per facet`);
  facets[r.facet] = { p: r.pattern, conf: r.confidence, src: hosts(r.sources) };
}

const rows = src.rows.map((r, i) => {
  if (!CONF.has(r.confidence)) throw new Error(`rows[${i}]: bad confidence`);
  if (!CLASSES.has(r.sel.cls)) throw new Error(`rows[${i}]: bad cls ${r.sel.cls}`);
  if (!Array.isArray(r.sel.setIds) || r.sel.setIds.length === 0)
    throw new Error(`rows[${i}]: empty setIds`);
  if (r.sel.cls === 'normal' && (!Array.isArray(r.sel.cardIds) || r.sel.cardIds.length === 0))
    throw new Error(
      `rows[${i}]: cls 'normal' rows must name explicit cardIds — they override the ` +
        `catalog's no-foil declaration and must never claim whole sets`,
    );
  if (r.scope !== undefined && !SCOPES.has(r.scope))
    throw new Error(`rows[${i}]: bad scope ${r.scope}`);
  return {
    p: r.pattern,
    setIds: r.sel.setIds,
    cls: r.sel.cls,
    rar: r.sel.rarities?.map((x) => x.toLowerCase()) ?? null,
    kinds: r.sel.variantKinds ?? null,
    cards: r.sel.cardIds ?? null,
    sc: r.scope ?? null,
    conf: r.confidence,
    src: hosts(r.sources),
  };
});

const out = {
  $doc: [
    'DERIVED FILE - do not hand-edit. Generated by tools/build-assignments-index.mjs',
    `from data/foil-card-assignments.json (row_count ${src.row_count}, facet_count ${src.facet_rows.length}).`,
    'Trimmed for the SPA bundle: claims + quotes stripped, citations kept as hostnames.',
    'The research file is the source of record; regenerate after changing it.',
  ],
  generatedFrom: 'data/foil-card-assignments.json',
  rowCount: rows.length,
  facets,
  rows,
};

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, JSON.stringify(out, null, 1) + '\n');
console.log(`wrote ${OUT} (${rows.length} rows, ${Object.keys(facets).length} facets)`);
