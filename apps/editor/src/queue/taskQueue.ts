// ── The degrading lookups ──────────────────────────────────────────────────
//
// One rule, three functions: an id this build does not know renders AS ITSELF.
// Never a throw, never a blank, and never a silent drop — a contributor who can
// see "ink tile" on a card can at least read the card, and the page stays up
// for the hundred cards that are not new.

// `Object.hasOwn` rather than `map[id] ?? fallback`, and that is load-bearing
// rather than pedantry: `SKILL_LABEL['toString']` inherits a FUNCTION off the
// prototype, and React throws on a function child — so the plain `??` guard
// would have turned one adversarial slug back into the white screen it was
// written to prevent.

/** The badge and the one-line "what IS this", for a known type or any other. */
export function typeLabel(type: TaskTypeId): { badge: string; what: string } {
  if (Object.hasOwn(TYPE_LABEL, type)) return TYPE_LABEL[type as TaskType]
  return {
    badge: type,
    what:
      'This queue was generated by a newer build than the page you are looking at, which has no description for ' +
      'this kind of task yet. The card is the artifact’s own text, unedited.',
  }
}

/** The skill's human name, or the raw slug when the artifact is ahead of us. */
export function skillLabel(skill: SkillId): string {
  return Object.hasOwn(SKILL_LABEL, skill) ? SKILL_LABEL[skill as Skill] : skill
}

/** The estimate in words, or the raw tier when the artifact is ahead of us. */
export function estimateLabel(estimate: EstimateId): string {
  return Object.hasOwn(ESTIMATE_LABEL, estimate) ? ESTIMATE_LABEL[estimate as Estimate] : estimate
}

/**
 * The chip order for a list of tasks: the ids THIS build knows, in the order a
 * contributor scans them, followed by any id only the artifact knows, in the
 * order it first appears.
 *
 * Appending rather than dropping is the point. A filter row built purely from
 * `TYPE_ORDER` would silently have no chip for a new kind, so its cards could
 * be read but never isolated — a filter that quietly cannot express part of the
 * list it filters.
 */
function orderFor<T extends string>(known: readonly T[], present: readonly string[]): string[] {
  const out: string[] = [...known]
  for (const id of present) if (!out.includes(id)) out.push(id)
  return out
}

export function typeOrderFor(tasks: Task[]): string[] {
  return orderFor(TYPE_ORDER, tasks.map((t) => t.type))
}

export function skillOrderFor(tasks: Task[]): string[] {
  return orderFor(SKILL_ORDER, tasks.map((t) => t.skill))
}

export interface Filters {
  /** null = every skill. */
  skill: SkillId | null
  /** null = every type. */
  type: TaskTypeId | null
}

/**
 * Apply the filters. The artifact is already sorted by impact, so this
 * PRESERVES ORDER rather than re-sorting — a filtered list that re-ranked
 * itself would show a different "most valuable next thing" depending on which
 * chip happened to be pressed, which is the opposite of what a ranking is for.
 */
export function filterTasks(tasks: Task[], f: Filters): Task[] {
  return tasks.filter((t) => (f.skill === null || t.skill === f.skill) && (f.type === null || t.type === f.type))
}

/**
 * How many cards each chip would show, given the OTHER filter.
 *
 * Counted against the co-filter rather than against everything, so a chip that
 * would produce an empty list can be shown as empty before it is pressed. A
 * dead-end control that only reveals itself after a click is worse than one
 * that says so.
 */
export function chipCounts(tasks: Task[], f: Filters): { skills: Record<string, number>; types: Record<string, number> } {
  const skills: Record<string, number> = {}
  const types: Record<string, number> = {}
  for (const t of tasks) {
    if (f.type === null || t.type === f.type) skills[t.skill] = (skills[t.skill] ?? 0) + 1
    if (f.skill === null || t.skill === f.skill) types[t.type] = (types[t.type] ?? 0) + 1
  }
  return { skills, types }
}

/** Printings governed by a list of cards; unsizeable cards contribute nothing. */
export function impactOf(tasks: Task[]): number {
  return tasks.reduce((n, t) => n + (t.impact ?? 0), 0)
}
