//
// The contribution queue, client side: the artifact's shape and the two pure
// functions that turn it into what the page shows.
//
// Everything here is PURE and separate from the rendering on purpose. "Does
// the skill filter show the right cards" and "does the type filter compose
// with it" are questions about a list, and answering them in a unit test is
// cheaper and more exact than answering them in a browser — the E2E run then
// only has to prove the control is wired to the function, not that the
// function is right.
//
// NOTHING IS COMPUTED HERE. Impact, estimate, skill, guards and the sort order
// are all decided by tools/task-queue/build.ts and baked into the artifact, so
// the page and the CLI can never disagree about what the queue says. This file
// filters and counts; it does not rank.
//
// ── THE ARTIFACT CAN BE NEWER THAN THIS CLIENT ─────────────────────────────
//
// `task-queue.json` is a BUILD OUTPUT fetched at runtime, and the two halves
// can ship apart: a bake regenerated by a newer builder, a cached bundle, an
// SPA rolled back while the data was not. So the unions below are what THIS
// build knows, never what the file may contain — the ids are widened with
// `& {}` (which keeps the literals as autocomplete hints while admitting any
// string), and every label lookup goes through `typeLabel` / `skillLabel` /
// `estimateLabel`, which degrade to the raw slug.
//
// That is not defensive decoration. `TYPE_LABEL[task.type].what` on a type this
// build had never heard of threw during render, React unmounted the tree, and
// the production queue — the editor's LANDING PAGE — went white while every
// test in the repository passed, because the fixture happened to rank the new
// cards off the first screen. A card must render degraded-but-alive instead,
// and a chip must appear for the unknown kind rather than hiding its cards
// behind a control that is not there.

/** The tiers, in the order a contributor scans them. Matches build.ts. */
export type Estimate = 'minutes' | 'half-hour' | 'hours'

export type Skill = 'mask' | 'slider' | 'glsl' | 'research' | 'live-tilt' | 'art'

export type TaskType =
  | 'approximation'
  | 'canon'
  | 'verdict'
  | 'mask'
  | 'window-mask'
  | 'residual'
  | 'empty-pool'
  | 'ink-tile'

/**
 * What the ARTIFACT can actually carry: one of the ids above, or one a newer
 * builder emitted. `& {}` is the idiom that widens the union to `string`
 * without losing the literals as editor hints.
 */
export type SkillId = Skill | (string & {})
export type TaskTypeId = TaskType | (string & {})
export type EstimateId = Estimate | (string & {})

export interface Task {
  id: string
  type: TaskTypeId
  title: string
  need: string
  skill: SkillId
  estimate: EstimateId
  estimateWhy: string
  impact: number | null
  impactWhy: string
  link: string | null
  source: string
  guards: string[]
  tieBreak: number
  detail: Record<string, string | number | boolean | null>
}

export interface EmptyPool {
  patternId: string
  reason: string
  detail: string
  citedPrintings: number
  alternates: number
  outrankedBy: { patternId: string; printings: number }[]
  implies: string
}

export interface Reconciliation {
  key: string
  claim: string
  claimedAt: string
  measured: string
  agrees: boolean
  note: string
}

export interface TaskQueueFile {
  version: number
  generatedAt: string
  source: string | null
  resolverVersion: number | null
  skills: Record<string, string>
  guards: Record<string, string>
  estimateTiers: Record<string, string>
  bakedInputs: Record<string, boolean>
  counts: {
    tasks: number
    byType: Record<string, number>
    bySkill: Record<string, number>
    impactTotal: number
    unsized: number
  }
  reconciliation: Reconciliation[]
  emptyPools: EmptyPool[]
  tasks: Task[]
}

